const { test, before, after } = require('node:test')
const assert = require('node:assert/strict')
const request = require('supertest')
const { openDatabase } = require('../database')
const { createApp } = require('../app')
let db, app, agent, another
const valid = { title: 'Test Game', description: 'Хорошее тестовое описание игры.', imageUrl: 'https://example.com/cover.png', gameUrl: 'https://example.com/game', genre: 'Экшен', platform: 'PC', releaseDate: '2024-02-29', status: 'draft' }
const wait = () => new Promise(resolve => setTimeout(resolve, 770))
before(() => { db = openDatabase(':memory:'); app = createApp(db); agent = request.agent(app); another = request.agent(app) })
after(() => db.close())
test('создание, чтение, редактирование своей записи и удаление', async () => {
  const created = await agent.post('/api/games').send(valid).expect(201)
  assert.equal(created.body.title, 'Test Game')
  await agent.get(`/api/games/${created.body.id}`).expect(200)
  await wait()
  const edited = await agent.patch(`/api/games/${created.body.id}`).send({ title: ' test game ' }).expect(200)
  assert.equal(edited.body.title, 'test game')
  await wait()
  await agent.delete(`/api/games/${created.body.id}`).expect(204)
  await agent.get(`/api/games/${created.body.id}`).expect(404)
  await wait()
  await agent.delete(`/api/games/${created.body.id}`).expect(404)
})
test('валидация и повторяющееся название', async () => {
  await wait()
  const bad = await agent.post('/api/games').send({ ...valid, title: ' ', gameUrl: 'javascript:alert(1)' }).expect(400)
  assert.equal(bad.body.error.code, 'VALIDATION')
  assert.ok(bad.body.error.details.gameUrl)
  await wait()
  await agent.post('/api/games').send({ ...valid, title: 'Unique Game' }).expect(201)
  await wait()
  const duplicate = await agent.post('/api/games').send({ ...valid, title: ' unique game ' }).expect(409)
  assert.equal(duplicate.body.error.code, 'DUPLICATE')
  await wait()
  await agent.post('/api/games').send({ ...valid, title: 'Русская Игра' }).expect(201)
  await wait()
  await agent.post('/api/games').send({ ...valid, title: ' русская игра ' }).expect(409)
})
test('поиск, фильтры, сортировка и пагинация работают совместно', async () => {
  const filtered = await agent.get('/api/games?search=%20%20hades%20&genre=Экшен&platform=PC&status=published').expect(200)
  assert.equal(filtered.body.pagination.total, 1)
  assert.equal(filtered.body.items[0].title, 'Hades')
  const unicode = await agent.get('/api/games?search=РУССКАЯ').expect(200)
  assert.equal(unicode.body.pagination.total, 1)
  const page = await agent.get('/api/games?sort=title&limit=5&page=2').expect(200)
  assert.equal(page.body.items.length, 5)
  assert.equal(page.body.pagination.page, 2)
  assert.ok(page.body.items[0].title.localeCompare(page.body.items[1].title, 'en') <= 0)
  await agent.get('/api/games?page=-1').expect(400)
  await agent.get('/api/games/nope').expect(400)
})
test('демонстрационные сессии изолированы и могут быть восстановлены', async () => {
  const first = await agent.get('/api/stats').expect(200)
  const second = await another.get('/api/stats').expect(200)
  assert.equal(first.body.total, second.body.total + 2)
  await wait()
  await agent.post('/api/demo/reset').expect(200)
  const restored = await agent.get('/api/stats').expect(200)
  assert.equal(restored.body.total, second.body.total)
  const unchanged = await another.get('/api/stats').expect(200)
  assert.equal(unchanged.body.total, second.body.total)
})
test('CORS preflight и ограничение тела', async () => {
  const health = await request(app).get('/api/health').expect(200)
  assert.equal(health.headers['set-cookie'], undefined)
  const preflight = await request(app).options('/api/games').set('Origin', 'http://localhost:5173').expect(204)
  assert.equal(preflight.headers['access-control-allow-origin'], 'http://localhost:5173')
  const huge = await request(app).post('/api/games').set('Content-Type','application/json').send({ title: 'x'.repeat(20000) }).expect(413)
  assert.equal(huge.body.error.code, 'BODY_TOO_LARGE')
})
